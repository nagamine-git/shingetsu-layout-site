function stageOf(reading: string): number {
  return Math.max(...Array.from(reading, (kana): number => {
    const stage = curriculum.findIndex((entry): boolean => entry.kana.includes(kana));
    if (stage === -1) throw new Error(`Unsupported curriculum character: ${kana}`);
    return stage;
  }));
}

function parseRows(rows: string, topic: string, prefix: string, benchmark = false): Passage[] {
  return rows.split("\n").map((row, index): Passage => {
    const [text, reading] = row.split("|");
    return { id: `${prefix}-${index}`, text, reading, topic, stage: stageOf(reading), benchmark };
  });
}

export const trainingCorpus: Passage[] = originals.flatMap(([topic, rows], index): Passage[] => parseRows(rows, topic, `p${index}`));
export const benchmarkCorpus: Passage[] = parseRows(benchmarkRows, "定点測定 v1", "benchmark", true);
